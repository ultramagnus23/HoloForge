"""
Run every mechanical pre-submission check and write PRE_SUBMIT_CHECKLIST.md
with the actual results, so the checklist records what was measured rather
than what someone remembered to tick.

Checks:
  1. compile        manuscript, supplement and cover letter built cleanly, with
                    no LaTeX error, no undefined reference or citation, and no
                    [PENDING] macro reaching a PDF
  2. page counts    universal template and the two-column journal layout, which
                    is what Applied Optics bills overlength against
  3. abstract       word count, with numbers.tex macros expanded
  4. figure order   every figure is first referenced in numerical order, and
                    every figure file that exists is actually used
  5. citations      every \\cite key resolves to a refs.bib entry, every entry
                    is cited, and every entry carries a DOI or URL
  6. no JOSA        the string does not survive anywhere it would be wrong
  7. no em dashes   in the manuscript, supplement, cover letter or the
                    author-facing markdown

This script does not compile anything itself. It reads the LaTeX logs left in
part2/paper/ by a compile there, and fails if one is missing or older than the
sources it was built from. Compile the three documents in paper/ first.

Usage (from part2/code): python scripts/pre_submit_check.py
Exit code 0 if every check passes, 1 otherwise.
"""
from __future__ import annotations

import datetime
import io
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
PAPER = os.path.join(ROOT, "paper")
REPO = os.path.normpath(os.path.join(ROOT, ".."))
OUT_PATH = os.path.join(PAPER, "PRE_SUBMIT_CHECKLIST.md")

DOCS = ("manuscript", "supplement", "cover_letter")
DASHES = "\u2014\u2013\u2012"

# "JOSA" is legitimate in these: Optica's own template defines \josa/\josaa/
# \josab abbreviation macros, refs.bib and the provenance notes record real
# JOSA A and JOSA B citations and the history of two that were wrong, and the
# Applied Optics submission documents disclose the earlier JOSA A submission
# on purpose.
JOSA_ALLOWED = {
    "part2/paper/optica-article.cls",
    "part2/paper/opticajnl.cls",
    "part2/paper/refs.bib",
    "part2/paper/SUBMISSION_GUIDE.md",
    "part2/paper/SUGGESTED_REVIEWERS.md",
    "part2/paper/RELEASE_NOTES_v2.1.0.md",
    "part2/paper/REVIEW_NOTES.md",
    "part2/paper/FORM_FIELDS.md",
    "part2/paper/PRE_SUBMIT_CHECKLIST.md",
    "part2/paper/cover_letter.tex",
    "part2/code/CHANGELOG.md",
    "part2/code/configs/media/pva_aa_405nm.yaml",
    "part2/code/docs/parameter_provenance.md",
    "part2/code/scripts/pre_submit_check.py",
    "part2/code/data/literature/DIGITIZE_TODO.md",
}

results: list[tuple[str, bool, str]] = []


def check(name: str, ok: bool, detail: str) -> bool:
    results.append((name, ok, detail))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {detail}")
    return ok


def read(path: str) -> str:
    return io.open(path, encoding="utf-8", errors="replace").read()


def pages_from_log(stem: str):
    log = os.path.join(PAPER, stem + ".log")
    if not os.path.exists(log):
        return None
    m = re.findall(r"Output written on .*?\((\d+) pages?", read(log))
    return int(m[-1]) if m else None


def check_compile() -> None:
    bad = []
    # numbers.tex is regenerated by make_numbers_tex.py and then appended to
    # by the two analysis scripts, so a log older than it was built against a
    # different set of macros and says nothing about the current sources.
    newest_source = max(os.path.getmtime(os.path.join(PAPER, f))
                        for f in ("numbers.tex", "refs.bib"))
    for doc in DOCS:
        log = os.path.join(PAPER, doc + ".log")
        tex = os.path.join(PAPER, doc + ".tex")
        if not os.path.exists(log):
            bad.append(f"{doc}: no log, compile it in paper/ first")
            continue
        if os.path.getmtime(log) < max(newest_source, os.path.getmtime(tex)):
            bad.append(f"{doc}: log is older than its sources, so it is stale; "
                       f"recompile in paper/")
            continue
        text = read(log)
        if re.search(r"^! ", text, re.M):
            bad.append(f"{doc}: LaTeX error")
        if "Undefined control sequence" in text:
            bad.append(f"{doc}: undefined control sequence")
        for kind in ("Reference", "Citation"):
            if re.search(rf"LaTeX Warning: {kind} .* undefined", text):
                bad.append(f"{doc}: undefined {kind.lower()}")
        pdf = os.path.join(PAPER, doc + ".pdf")
        if not os.path.exists(pdf):
            bad.append(f"{doc}: no PDF")
    check("compile", not bad, "; ".join(bad) if bad else
          "manuscript, supplement and cover letter built with no error, "
          "undefined reference or undefined citation")

    pending = [d for d in DOCS if "PENDING" in read(os.path.join(PAPER, d + ".tex"))]
    numbers = read(os.path.join(PAPER, "numbers.tex"))
    # numbers.tex mentions the flag in a trailing comment where it loads
    # xcolor, so a bare substring search false-positives. Count only the exact
    # form make_numbers_tex.py emits for a missing value.
    n_pending = numbers.count(r"\textcolor{red}{[PENDING]}")
    check("no PENDING macros", not pending and n_pending == 0,
          "no [PENDING] macro in numbers.tex or any source"
          if not pending and n_pending == 0
          else f"{n_pending} PENDING in numbers.tex, sources: {pending}")


def check_pages() -> None:
    uni = pages_from_log("manuscript")
    jour = pages_from_log("manuscript_lengthcheck")
    supp = pages_from_log("supplement")
    cover = pages_from_log("cover_letter")
    check("journal page count", jour is not None and jour <= 10,
          f"{jour} published pages in the two-column journal layout "
          f"(Applied Optics limit 10, $300 per page beyond); universal "
          f"template {uni}, supplement {supp}")
    check("cover letter length", cover == 1,
          f"{cover} page" if cover else "no cover_letter.log")


def check_abstract() -> None:
    src = read(os.path.join(PAPER, "manuscript.tex"))
    nums = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{(.*?)\}\n",
                           read(os.path.join(PAPER, "numbers.tex"))))
    body = re.search(r"\\begin\{abstract\*\}(.*?)\\end\{abstract\*\}", src, re.S).group(1)
    body = re.sub(r"\\(\w+)\{\}", lambda m: nums.get(m.group(1), ""), body)
    body = re.sub(r"\\(\w+)", lambda m: nums.get(m.group(1), " "), body)
    n = len(body.replace("\\", " ").replace("~", " ").replace("$", "").split())
    check("abstract word count", 85 <= n <= 115,
          f"{n} words (target about 100)")


def check_figure_order() -> None:
    problems = []
    for doc, pat in (("manuscript", r"fig:"), ("supplement", r"fig:s")):
        src = read(os.path.join(PAPER, doc + ".tex"))
        declared = re.findall(r"\\label\{(fig:[^}]+)\}", src)
        order = {lab: i for i, lab in enumerate(declared)}
        seen, last = set(), -1
        for lab in re.findall(r"\\ref\{(fig:[^}]+)\}", src):
            if lab not in order or lab in seen:
                continue
            seen.add(lab)
            if order[lab] < last:
                problems.append(f"{doc}: {lab} first referenced out of order")
            last = max(last, order[lab])
        unused = [lab for lab in declared if lab not in seen]
        if unused:
            problems.append(f"{doc}: never referenced: {unused}")
    # every figure PDF on disk is included by one of the documents
    figdir = os.path.join(ROOT, "code", "figures", "paper")
    included = set()
    for doc in ("manuscript", "supplement"):
        included |= set(re.findall(r"figures/paper/([^}]+\.pdf)",
                                   read(os.path.join(PAPER, doc + ".tex"))))
    orphan = sorted(set(os.listdir(figdir)) - included)
    if orphan:
        problems.append(f"figure files not used by any document: {orphan}")
    check("figure order", not problems,
          "; ".join(problems) if problems else
          f"{len(included)} figures, each first referenced in numerical order "
          f"and no orphan figure files")


def check_citations() -> None:
    bib = read(os.path.join(PAPER, "refs.bib"))
    bib_no_comments = "\n".join(l for l in bib.splitlines() if not l.lstrip().startswith("%"))
    entries = dict(re.findall(r"@\w+\{([^,]+),(.*?)\n\}", bib_no_comments, re.S))
    cited = set()
    for doc in ("manuscript", "supplement"):
        for group in re.findall(r"\\cite\{([^}]+)\}", read(os.path.join(PAPER, doc + ".tex"))):
            cited |= {k.strip() for k in group.split(",")}
    missing = sorted(cited - set(entries))
    unused = sorted(set(entries) - cited)
    no_doi = sorted(k for k, body in entries.items()
                    if "doi" not in body.lower() and "url" not in body.lower())
    ok = not missing and not unused
    detail = (f"{len(entries)} entries, every cite key resolved, every entry "
              f"cited" if ok else
              f"missing from refs.bib: {missing}; in refs.bib but never "
              f"cited: {unused}")
    check("citations", ok, detail)
    # Not a gate: opticajnl.bst does not print DOI fields and Optica resolves
    # them at production. Recorded so the gap stays visible.
    check("DOI coverage (advisory)", True,
          f"{len(entries) - len(no_doi)} of {len(entries)} entries carry a DOI "
          f"or URL field; the rest are identified by author, title, venue and "
          f"year only: {no_doi}" if no_doi else "every entry carries a DOI or URL")


def _tracked_files() -> list[str]:
    out = subprocess.run(["git", "ls-files"], cwd=REPO, capture_output=True,
                         text=True).stdout
    return [p for p in out.splitlines() if p]


def check_no_josa() -> None:
    offenders = []
    for rel in _tracked_files():
        if rel in JOSA_ALLOWED:
            continue
        # The built package under part2/submission/ is copies of files that
        # are checked at their source in part2/paper/; checking them twice
        # only reports the allowed disclosure a second time.
        if rel.startswith("part2/submission/"):
            continue
        path = os.path.join(REPO, rel)
        if not os.path.isfile(path):
            continue
        try:
            text = read(path)
        except (UnicodeDecodeError, OSError):
            continue
        if re.search(r"JOSA|Journal of the Optical Society of America A|Korotkova",
                     text):
            offenders.append(rel)
    check("no JOSA outside the disclosure", not offenders,
          f"found in {offenders}" if offenders else
          f"clean across {len(_tracked_files())} tracked files "
          f"({len(JOSA_ALLOWED)} files allowed to mention it: real JOSA "
          f"citations, Optica's own template macros, and the documents that "
          f"disclose the earlier submission on purpose)")


def check_no_em_dashes() -> None:
    targets = [os.path.join(PAPER, d + ".tex") for d in DOCS]
    targets += [os.path.join(PAPER, f) for f in
                ("SUBMISSION_GUIDE.md", "SUGGESTED_REVIEWERS.md",
                 "RELEASE_NOTES_v2.1.0.md", "REVIEW_NOTES.md", "FORM_FIELDS.md")]
    targets.append(os.path.join(ROOT, "code", "data", "literature",
                                "DIGITIZE_TODO.md"))
    offenders = []
    for path in targets:
        if not os.path.exists(path):
            continue
        text = read(path)
        n = sum(text.count(c) for c in DASHES)
        # "--" is an en dash in LaTeX source and is used for numeric ranges,
        # which is typographically correct and is not what the rule targets.
        if n:
            offenders.append(f"{os.path.basename(path)}:{n}")
    check("no em dashes", not offenders,
          f"found: {offenders}" if offenders else
          f"none in {len(targets)} author-facing files")


def main() -> int:
    print("pre-submission checks\n")
    check_compile()
    check_pages()
    check_abstract()
    check_figure_order()
    check_citations()
    check_no_josa()
    check_no_em_dashes()

    passed = sum(1 for _, ok, _ in results if ok)
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "# Pre-submission checklist (Applied Optics)",
        "",
        f"Generated by `scripts/pre_submit_check.py` on {stamp}. Re-run it "
        "after any change; do not edit this file by hand.",
        "",
        f"**{passed} of {len(results)} checks pass.**",
        "",
        "| Check | Result | Detail |",
        "| --- | --- | --- |",
    ]
    for name, ok, detail in results:
        lines.append(f"| {name} | {'pass' if ok else 'FAIL'} | {detail} |")
    lines += [
        "",
        "## What this script cannot check",
        "",
        "These remain the author's responsibility and are listed in",
        "`SUBMISSION_GUIDE.md`, Section 3:",
        "",
        "- That every DOI resolves and every author list, year and venue is",
        "  correct. The bibliography was verified entry by entry for the",
        "  earlier submission and no citation has been added since; the script",
        "  only confirms that each entry exists, is cited, and carries a DOI",
        "  or URL.",
        "- That the manuscript and supplement read correctly end to end.",
        "- That the generative-AI disclosure in the Acknowledgment is complete.",
        "- That the JOSA A decision letter is saved as a PDF for the",
        "  previously-submitted question in Prism.",
        "- That the Zenodo release has been created from the merged branch.",
        "",
    ]
    io.open(OUT_PATH, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(f"\nwrote {OUT_PATH}")
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    sys.exit(main())
